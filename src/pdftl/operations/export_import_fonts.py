"""
Operations for exporting and importing fonts and their metadata from/to PDFs.

Registered Operations:
  - export_fonts
  - import_fonts

The actual "how" of these operations lives in pdftl/operations/helpers/:
  - font_ops_shared.py    shared helpers (hashing, name sanitizing, page resolution)
  - font_export_helpers.py   export-side logic (manifest building, sidecar writing)
  - font_import_helpers.py   import-side logic (stream writing, widths sync, etc.)

Pure fontTools-based binary manipulation (reading/patching/squashing metrics
directly inside a TTF/OTF file) lives in pdftl/fonts/font_binary_utils.py,
alongside the codebase's other stateless font-domain utilities.
"""

