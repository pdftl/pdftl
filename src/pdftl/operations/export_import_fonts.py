def export_fonts_cli_hook(result: OpResult, stage, _pipeline):
    """Writes the manifest data to stdout or a file in JSON."""
    if not result.success:
        return

    output_file = from_result_meta(result, c.META_OUTPUT_FILE)
    from pdftl.utils.string_utils import compact_json_string

    with smart_open_maybe_dash(output_file) as file:
        json_string = compact_json_string(json.dumps(result.data, indent=2), fold_dicts=False)
        file.write(json_string + "\n")


@register_operation(
    "export_fonts",
    tags=["info", "metadata", "fonts", "export"],
    type="single input operation",
    desc="Export fonts and a JSON manifest for external editing",
    long_desc=_EXPORT_FONTS_LONG_DESC,
    examples=_EXPORT_FONTS_EXAMPLES,
    cli_hook=export_fonts_cli_hook,
    usage="<input> export_fonts [<spec>...] <dir> [output <output>]",
    args=([c.INPUT_PDF, c.OPERATION_ARGS], {"output_file": c.OUTPUT}),
    skip_pipeline_save=True,
)
def export_fonts(pdf, specs, output_file=None) -> OpResult:
    """Export fonts with unified sidecar mappings and metrics."""
    raw_tokens: list[str] = []
    parse_keyval_list(
        specs or [],
        bare_tokens=raw_tokens,
        allowed_keys=["tounicode"],
        context="export_fonts",
    )

    ensure_dependencies(
        feature_name="export_fonts",
        dependencies={"fontTools": "fonttools"},
        extra_tag="export-fonts",
    )

    tounicode_mode = "json"
    for arg in specs or []:
        if arg.startswith("tounicode="):
            tounicode_mode = arg.split("=")[1].strip().lower()

    if tounicode_mode not in ("json", "ps", "all"):
        raise InvalidArgumentError(
            f"Invalid tounicode mode: '{tounicode_mode}'. Choose from: json, ps, all"
        )

    # Filter out tounicode kwarg to isolate directory tokens
    clean_tokens = [t for t in raw_tokens if not t.startswith("tounicode=")]
    if not clean_tokens:
        raise InvalidArgumentError("Missing required directory argument.")

    out_dir_str = clean_tokens[-1]
    page_specs = clean_tokens[:-1]

    out_dir = Path(out_dir_str)
    out_dir.mkdir(parents=True, exist_ok=True)

    target_pages = get_target_pages(pdf, page_specs)
    manifest = build_manifest(pdf, target_pages, out_dir, tounicode_mode)

    resolved_output = output_file if output_file is not None else str(out_dir / "manifest.json")

    return OpResult(
        success=True,
        data=manifest,
        meta={c.META_OUTPUT_FILE: resolved_output},
    )


