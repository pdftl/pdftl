def _process_single_font_import(
    pdf: pikepdf.Pdf, font_entry: dict, out_dir: Path, pikepdf_mod: Any
) -> bool:
    """Helper orchestrator to process a single font entry from the manifest."""
    obj_id = font_entry["obj_id"]
    gen_id = font_entry["gen_id"]

    try:
        font_obj = pdf.get_object((obj_id, gen_id))
    except (pikepdf_mod.PdfError, KeyError):
        font_obj = None

    if font_obj is None:
        logger.warning("Font object (%d:%d) defined in manifest not found in PDF.", obj_id, gen_id)
        return False

    binary_updated = import_single_font_binary(font_obj, font_entry, out_dir)
    mappings = import_tounicode_and_get_mappings(font_obj, font_entry, out_dir, pikepdf_mod, pdf)
    import_differences(font_obj, font_entry, pikepdf_mod)
    encoding_cmap_updated = import_encoding_cmap(font_obj, font_entry, pikepdf_mod)
    cid_to_gid_updated = import_cid_to_gid_map(font_obj, font_entry, out_dir, pikepdf_mod, pdf)

    # Update structural font descriptor properties
    from pdftl.operations.helpers.font_import_helpers import import_descriptor

    descriptor_updated = import_descriptor(font_obj, font_entry, out_dir, pikepdf_mod)

    if font_entry.get("subtype") == "Type3":
        from pdftl.operations.helpers.font_import_helpers import import_type3_font

        import_type3_font(font_obj, font_entry, out_dir)
        binary_updated = True

    inmemory_updated = import_widths(font_obj, font_entry, out_dir, mappings, pikepdf_mod)

    return (
        binary_updated
        or inmemory_updated
        or cid_to_gid_updated
        or descriptor_updated
        or encoding_cmap_updated
    )


@register_operation(
    "import_fonts",
    tags=["in_place", "fonts", "import", "replace"],
    type="single input operation",
    desc="Import edited fonts from a directory using a JSON manifest",
    long_desc=_IMPORT_FONTS_LONG_DESC,
    usage="<input> import_fonts <dir> [manifest=<manifest.json>] output <out.pdf>",
    examples=_IMPORT_FONTS_EXAMPLES,
    args=([c.INPUT_PDF, c.OPERATION_ARGS], {}),
)
def import_fonts(pdf: pikepdf.Pdf, specs: list[str]) -> OpResult:
    import pikepdf

    raw_tokens: list[str] = []
    kv = parse_keyval_list(
        specs or [],
        bare_tokens=raw_tokens,
        allowed_keys=["manifest"],
        context="import_fonts",
    )

    ensure_dependencies(
        feature_name="export_fonts",
        dependencies={"fontTools": "fonttools"},
        extra_tag="import-fonts",
    )

    if not raw_tokens:
        raise InvalidArgumentError("Missing required directory argument.")

    out_dir_str = raw_tokens[0]
    out_dir = Path(out_dir_str)
    if not out_dir.is_dir():
        raise InvalidArgumentError(f"Target directory does not exist: {out_dir}")

    manifest_str = kv.get("manifest")
    manifest_path = out_dir / "manifest.json" if not manifest_str else Path(manifest_str)

    if not manifest_path.is_file():
        raise InvalidArgumentError(f"Manifest file not found: {manifest_path}")

    try:
        with open(manifest_path, encoding="utf-8") as f:
            manifest = json.load(f)
    except json.JSONDecodeError as exc:
        raise InvalidArgumentError(f"Invalid JSON manifest: {exc}") from exc

    fonts = manifest.get("fonts", {})
    if not fonts:
        logger.info("Manifest contains no font records. Skipping import.")
        return OpResult(success=True, pdf=pdf)

    updated_count = sum(
        1
        for _, font_entry in fonts.items()
        if _process_single_font_import(pdf, font_entry, out_dir, pikepdf)
    )

    logger.info("Successfully processed font updates. %d binary stream(s) updated.", updated_count)
    return OpResult(success=True, pdf=pdf)
