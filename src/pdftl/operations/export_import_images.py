def _parse_quality(quality_str: str) -> int:
    """Parses and validates JPEG compression quality bounds."""
    try:
        quality = int(quality_str)
        if not (1 <= quality <= 100):
            raise ValueError
        return quality
    except ValueError as exc:
        raise InvalidArgumentError(
            f"Invalid quality: '{quality_str}'. Must be an integer between 1 and 100."
        ) from exc


def _read_manifest(manifest_path: Path) -> dict:
    """Loads JSON manifest from the file system or standard input."""
    if str(manifest_path) == "-":
        try:
            return json.load(sys.stdin)
        except json.JSONDecodeError as exc:
            raise InvalidArgumentError(f"Invalid JSON manifest from stdin: {exc}") from exc

    if not manifest_path.is_file():
        raise InvalidArgumentError(f"Manifest file not found: {manifest_path}")

    try:
        with open(manifest_path, encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as exc:
        raise InvalidArgumentError(f"Invalid JSON manifest: {exc}") from exc


def _get_pdf_image_objects(pdf) -> dict:
    """Crawls active internal PDF stream resources to index target XObjects."""
    import pikepdf

    objgen_map = {}
    for obj in pdf.objects:
        if (
            isinstance(obj, pikepdf.Stream)
            and obj.get(pikepdf.Name.Type) == pikepdf.Name.XObject
            and obj.get(pikepdf.Name.Subtype) == pikepdf.Name.Image
        ):
            obj_id = f"{obj.objgen[0]}_{obj.objgen[1]}"
            objgen_map[obj_id] = obj
    return objgen_map


def _check_dimensions(filename: str, pil_img, stream_info: dict) -> None:
    """Checks for dimension shifts that might cause layout distortions."""
    orig_w = stream_info.get("width_px")
    orig_h = stream_info.get("height_px")
    if orig_w and orig_h and (pil_img.width != orig_w or pil_img.height != orig_h):
        logger.warning(
            "Imported image %s dimensions (%dx%d) differ from original (%dx%d). "
            "This may cause visual distortion in the PDF layout.",
            filename,
            pil_img.width,
            pil_img.height,
            orig_w,
            orig_h,
        )


def _resolve_import_filepath(filename: str, out_dir: Path) -> Path | None:
    """Checks and resolves format suffix swaps (e.g. .jpg -> .png conversions)."""
    # Security: Prevent Path Traversal attacks via custom filenames inside the manifest.
    try:
        filepath = Path(out_dir / filename).resolve()
    except (OSError, ValueError) as exc:
        logger.debug("Failed to resolve filename path %s: %s", filename, exc)
        return None

    if not filepath.is_relative_to(out_dir.resolve()):
        raise InvalidArgumentError(
            f"Security violation: path traversal detected in filename '{filename}'"
        )

    if filepath.is_file():
        return filepath

    # Extended Extension Fallback Cycle
    supported_exts = {".png", ".jpg", ".jpeg", ".webp"}
    for ext in supported_exts:
        alt_filepath = filepath.with_suffix(ext)
        if alt_filepath.is_file():
            logger.info("Using alternative format file: %s", alt_filepath.name)
            return alt_filepath

    logger.debug("Skipping %s, file not found in directory.", filename)
    return None


def _import_single_image(
    obj_id: str,
    stream_info: dict,
    out_dir: Path,
    objgen_map: dict,
    quality: int,
) -> bool:
    """Re-encodes and updates a single image stream from the manifest inside the PDF."""
    from PIL import Image

    filename = stream_info.get("export_file")
    if not filename:
        return False

    filepath = _resolve_import_filepath(filename, out_dir)
    if not filepath:
        return False

    current_hash = _file_hash(filepath)
    if current_hash == stream_info.get("file_hash"):
        logger.debug("Skipping %s, file hash unchanged.", filename)
        return False

    xobj = objgen_map.get(obj_id)
    if not xobj:
        logger.warning("Target stream %s from manifest not found in PDF.", obj_id)
        return False

    try:
        pil_img = Image.open(filepath)
        pil_img.load()
    except (OSError, ValueError) as exc:
        # Explanatory comment: Gracefully log and bypass unopenable/corrupt edited files.
        logger.warning("Failed to read image %s: %s", filepath, exc)
        return False

    _check_dimensions(filepath.name, pil_img, stream_info)

    # Resolve real original stream context metadata to satisfy encoder constraints
    placements = stream_info.get("placements", [])
    page_num = placements[0].get("page", 0) if placements else 0

    ctx = ImageContext(
        xobj=xobj,
        smask_xobj=xobj.get("/SMask"),
        orig_size=get_orig_stream_size(xobj),
        img_dict={"name": filepath.name},
        page_num=page_num,
    )

    try:
        encode_and_update_pdf_image(ctx, pil_img, quality)
        logger.info("Imported and updated image stream %s from %s", obj_id, filepath.name)
        return True
    except (OSError, ValueError) as exc:
        # Explanatory comment: Log encoder mapping or layout write errors gracefully.
        logger.warning("Failed to encode and update PDF image stream %s: %s", obj_id, exc)
        return False


@register_operation(
    "import_images",
    tags=["in_place", "images", "import", "replace"],
    type="single input operation",
    desc="Import edited images from a directory using a JSON manifest",
    long_desc=_IMPORT_IMAGES_LONG_DESC,
    usage="<input> import_images <dir> [manifest=<manifest.json>] [quality=<q>] output <out.pdf>",
    examples=_IMPORT_IMAGES_EXAMPLES,
    args=([c.INPUT_PDF, c.OPERATION_ARGS], {}),
)
def import_images(pdf, specs) -> OpResult:
    """Import edited images from a directory and overwrite internal PDF streams."""
    raw_tokens = []
    kv = parse_keyval_list(
        specs or [],
        bare_tokens=raw_tokens,
        allowed_keys=["manifest", "quality"],
        context="import_images",
    )

    out_dir_str, _ = _classify_tokens(raw_tokens)
    if not out_dir_str:
        raise InvalidArgumentError("Missing required directory argument.")

    out_dir = Path(out_dir_str)
    if not out_dir.is_dir():
        raise InvalidArgumentError(f"Target directory does not exist: {out_dir}")

    quality = _parse_quality(kv.get("quality", "75"))
    manifest_str = kv.get("manifest")

    manifest_path = out_dir / "manifest.json" if not manifest_str else Path(manifest_str)
    manifest = _read_manifest(manifest_path)

    image_streams = manifest.get("image_streams", {})
    if not image_streams:
        logger.info("Manifest contains no image streams. Skipping import.")
        return OpResult(success=True, pdf=pdf)

    objgen_map = _get_pdf_image_objects(pdf)
    updated_count = 0

    for obj_id, stream_info in image_streams.items():
        if _import_single_image(obj_id, stream_info, out_dir, objgen_map, quality):
            updated_count += 1

    logger.info("Successfully imported %d image(s).", updated_count)
    return OpResult(success=True, pdf=pdf)
