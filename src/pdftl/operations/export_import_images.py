def _get_target_pages(pdf, page_specs: list[str]) -> list[int]:
    """Resolves target page numbers from raw page specifications."""
    num_pages = len(pdf.pages)
    if page_specs:
        return sorted(list(page_numbers_matching_page_specs(page_specs, num_pages)))
    return list(range(1, num_pages + 1))


def _export_single_image(xobj, img: dict, out_dir: Path) -> tuple[str, str] | None:
    """Extracts a PDF XObject to a PIL Image and saves it to disk."""
    pil_img = extract_to_pil(xobj)
    if pil_img is None:
        logger.warning("Could not extract PIL image for object %s", xobj.objgen)
        return None

    fmt = img.get("format", "unknown")
    ext = "jpg" if fmt == "dctdecode" else "png"
    obj_id = f"{xobj.objgen[0]}_{xobj.objgen[1]}"
    filename = f"obj_{obj_id}.{ext}"
    filepath = out_dir / filename

    try:
        if pil_img.mode == "CMYK" and ext == "png":
            save_img = pil_img.convert("RGB")
        else:
            save_img = pil_img
        save_img.save(filepath)
    except (OSError, ValueError) as exc:
        # Explanatory comment: Gracefully handle Pillow save and file I/O failures.
        logger.warning("Failed to save image %s: %s", filepath, exc)
        return None

    return filename, _file_hash(filepath)


def _build_manifest(pdf, target_pages: list[int], out_dir: Path) -> dict:
    """Iterates over embedded PDF images and builds the manifest dictionary."""
    from pdftl.utils.images.finders import extract_pdf_images

    image_data = extract_pdf_images(pdf, target_pages)
    manifest: dict = {"image_streams": {}}

    for img in image_data:
        xobj = img.pop("xobj")

        # Inline Collision Guard: Skip direct objects to prevent mapping crashes
        if not xobj.is_indirect:
            logger.warning(
                "Skipping inline/direct image object on page %s. "
                "Only indirect image objects are supported.",
                img.get("page", "?"),
            )
            continue

        obj_id = f"{xobj.objgen[0]}_{xobj.objgen[1]}"

        placement = {
            "page": img["page"],
            "name": img["name"],
            "bbox": img["bbox"],
            "ppi_x": img["ppi_x"],
            "ppi_y": img["ppi_y"],
        }

        if obj_id not in manifest["image_streams"]:
            export_info = _export_single_image(xobj, img, out_dir)
            if export_info is None:
                continue

            filename, file_hash = export_info
            manifest["image_streams"][obj_id] = {
                "format": img.get("format", "unknown"),
                "width_px": img["width_px"],
                "height_px": img["height_px"],
                "colorspace": img["colorspace"],
                "bits": img["bits"],
                "export_file": filename,
                "file_hash": file_hash,
                "placements": [placement],
            }
        else:
            manifest["image_streams"][obj_id]["placements"].append(placement)

    return manifest


def export_images_cli_hook(result: OpResult, stage, _pipeline):
    """Writes the manifest data to stdout or a file in JSON."""
    if not result.success:
        return

    output_file = from_result_meta(result, c.META_OUTPUT_FILE)

    with smart_open_maybe_dash(output_file) as file:
        json_string = compact_json_string(json.dumps(result.data, indent=2), fold_dicts=False)
        file.write(json_string + "\n")


@register_operation(
    "export_images",
    tags=["info", "metadata", "images", "export"],
    type="single input operation",
    desc="Export images and a JSON manifest for external editing",
    long_desc=_EXPORT_IMAGES_LONG_DESC,
    examples=_EXPORT_IMAGES_EXAMPLES,
    cli_hook=export_images_cli_hook,
    usage="<input> export_images [<spec>...] <dir> [output <output>]",
    args=([c.INPUT_PDF, c.OPERATION_ARGS], {"output_file": c.OUTPUT}),
    skip_pipeline_save=True,
)
def export_images(pdf, specs, output_file=None) -> OpResult:
    """Export embedded images to a directory with a JSON manifest."""
    raw_tokens = []
    parse_keyval_list(
        specs or [],
        bare_tokens=raw_tokens,
        allowed_keys=[],
        context="export_images",
    )

    out_dir_str, page_specs = _classify_tokens(raw_tokens)
    if not out_dir_str:
        raise InvalidArgumentError("Missing required directory argument.")

    out_dir = Path(out_dir_str)
    out_dir.mkdir(parents=True, exist_ok=True)

    target_pages = _get_target_pages(pdf, page_specs)
    manifest = _build_manifest(pdf, target_pages, out_dir)

    resolved_output = output_file if output_file is not None else str(out_dir / "manifest.json")

    return OpResult(
        success=True,
        data=manifest,
        meta={c.META_OUTPUT_FILE: resolved_output},
    )


