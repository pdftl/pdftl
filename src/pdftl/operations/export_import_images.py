def _file_hash(filepath: Path) -> str:
    """Calculates the MD5 hash of a file to track modifications."""
    hasher = hashlib.md5()
    try:
        with open(filepath, "rb") as f:
            buf = f.read()
            hasher.update(buf)
    except OSError as exc:
        # Explanatory comment: Return empty hash if the file is unreadable,
        # which will safely force a re-import if attempted.
        logger.debug("Failed to calculate hash for %s: %s", filepath, exc)
        return ""
    return hasher.hexdigest()


def _classify_tokens(tokens: list[str]) -> tuple[str | None, list[str]]:
    """Separates the directory argument from page specifications based on typical naming
    formats."""
    if not tokens:
        return None, []
    if len(tokens) == 1:
        return tokens[0], []

    directory = None
    page_specs = []
    for t in reversed(tokens):  # last dir-like takes priority
        if directory is None and not is_valid_page_spec(t):
            directory = t
        else:
            page_specs.append(t)

    # Fallback if everything matched the page spec pattern
    if directory is None and page_specs:
        directory = page_specs.pop(0)

    return directory, page_specs


